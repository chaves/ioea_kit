/**
 * The `.webp` sibling of an uploaded image, for a `<source srcset>`.
 *
 * Spaces and commas are escaped because srcset treats a space as the start of a
 * descriptor and a comma as a candidate separator: "…/Coase Award 2015.webp"
 * parses as candidate "…/Coase" + descriptors, the browser drops it, and
 * silently falls back to the (larger) JPEG. Only those two characters are
 * touched, so already-encoded URLs are not double-encoded.
 */
export function toWebpUrl(imageUrl: string | null | undefined): string {
	if (!imageUrl) return '';
	return imageUrl
		.replace(/\.(jpe?g|png)(\?.*)?$/i, '.webp$2')
		.replace(/ /g, '%20')
		.replace(/,/g, '%2C');
}

/**
 * The 800px card thumbnail of a news image (`/images/news/thumbs/<name>.webp`),
 * or '' for images stored elsewhere, which have no thumbnail. Generated by
 * scripts/generate-thumbs.mjs at build time and by imageStore on upload.
 */
export function toThumbUrl(imageUrl: string | null | undefined): string {
	if (!imageUrl || !/^\/images\/news\/[^/]+\.(jpe?g|png)$/i.test(imageUrl.split('?')[0])) return '';
	return toWebpUrl(imageUrl).replace(/^\/images\/news\//, '/images/news/thumbs/');
}
